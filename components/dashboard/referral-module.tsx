'use client'

import { useState } from 'react'
import { Link2, Copy, Check } from 'lucide-react'
import { Button } from '@/components/ui/button'
import { GlassCard, CardHeading } from './glass-card'
import { cn } from '@/lib/utils'

const REF_LINK = 'https://sabafi.io/r/0x7a3F91cE'

const referrals = [
  { wallet: '0x4b2E…a91F', joined: 'Oct 02, 2026', active: true, volume: 18450 },
  { wallet: '0x91cA…03bD', joined: 'Sep 27, 2026', active: true, volume: 12300 },
  { wallet: '0xF0e1…7C22', joined: 'Sep 19, 2026', active: false, volume: 6720 },
  { wallet: '0x2D8a…e4A0', joined: 'Sep 11, 2026', active: true, volume: 5180 },
  { wallet: '0xAb77…1f9E', joined: 'Aug 30, 2026', active: false, volume: 2550 },
]

export function ReferralModule() {
  const [copied, setCopied] = useState(false)

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(REF_LINK)
    } catch {
      // Clipboard may be blocked inside sandboxed iframes; still show feedback.
    }
    setCopied(true)
    setTimeout(() => setCopied(false), 1800)
  }

  return (
    <GlassCard className="p-6">
      <CardHeading
        icon={<Link2 className="size-4" />}
        title="Affiliate Engine & Referred Users"
        description="Earn 5% of the yield generated by every player you refer."
      />

      <div className="mt-5 flex flex-col gap-2 sm:flex-row">
        <label htmlFor="ref-link" className="sr-only">
          Your referral link
        </label>
        <input
          id="ref-link"
          readOnly
          value={REF_LINK}
          onFocus={(e) => e.currentTarget.select()}
          className="h-11 flex-1 rounded-xl border border-border bg-background/60 px-4 font-mono text-sm text-foreground outline-none focus-visible:border-primary/60 focus-visible:ring-2 focus-visible:ring-primary/30"
        />
        <Button
          onClick={copy}
          className="h-11 rounded-xl px-5 font-semibold hover:bg-primary/90"
          aria-live="polite"
        >
          {copied ? <Check /> : <Copy />}
          {copied ? 'Copied' : 'Copy'}
        </Button>
      </div>

      <div className="mt-6 overflow-x-auto rounded-xl border border-border">
        <table className="w-full min-w-[520px] text-sm">
          <caption className="sr-only">Referred players</caption>
          <thead className="bg-secondary/50 text-left text-xs uppercase tracking-wider text-muted-foreground">
            <tr>
              <th scope="col" className="px-4 py-3 font-medium">Player Wallet</th>
              <th scope="col" className="px-4 py-3 font-medium">Joined</th>
              <th scope="col" className="px-4 py-3 font-medium">Status</th>
              <th scope="col" className="px-4 py-3 text-right font-medium">Volume</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-border">
            {referrals.map((r) => (
              <tr key={r.wallet} className="transition-colors hover:bg-secondary/30">
                <td className="px-4 py-3 font-mono text-foreground">{r.wallet}</td>
                <td className="px-4 py-3 text-muted-foreground">{r.joined}</td>
                <td className="px-4 py-3">
                  <span
                    className={cn(
                      'inline-flex items-center gap-1.5 rounded-md px-2 py-0.5 text-xs font-medium',
                      r.active
                        ? 'bg-success/10 text-success'
                        : 'bg-destructive/10 text-destructive',
                    )}
                  >
                    <span
                      className={cn('size-1.5 rounded-full', r.active ? 'bg-success' : 'bg-destructive')}
                      aria-hidden
                    />
                    {r.active ? 'Active' : 'Inactive'}
                  </span>
                </td>
                <td className="px-4 py-3 text-right font-mono text-foreground">
                  {r.volume.toLocaleString('en-US')}{' '}
                  <span className="text-xs text-muted-foreground">USDC</span>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </GlassCard>
  )
}
